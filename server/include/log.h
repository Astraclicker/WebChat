#pragma once
// ============================================================================
//  astra_log —— 一个轻量但功能完整的日志系统
// ============================================================================
//
//  设计目标
//  --------
//  1. 用起来简单：一个枚举表示等级，一个函数写日志。
//  2. 落地可靠：自动加时间戳和等级，格式化后同时写到 .log 文件和终端。
//  3. 用起来安全：多线程调用不会把日志写串行。
//  4. 长期可跑：日志文件超过指定大小时自动切分，不会无限膨胀。
//  5. 方便观察：内置计数，随时能知道一共写了多少条、各等级各多少条。
//
//
//  快速上手
//  --------
//      #include <log.h>
//
//      // 写法一：直接调函数，传内容和等级
//      astra_log::log("服务端启动", astra_log::Level::Info);
//
//      // 写法二：用 LOG 宏，可以像 cout 一样拼接任意变量
//      LOG(astra_log::Level::Warn, "磁盘剩余 ", percent, "%，低于阈值");
//
//
//  日志长什么样
//  ------------
//      [2026-09-27 14:03:22.123] [INFO] 服务端启动
//      [2026-09-27 14:03:23.008] [WARN] 磁盘剩余 8.5%，低于阈值
//
//  从左到右依次是：时间戳（精确到毫秒）、等级、日志内容。
//
//
//  等级怎么选
//  ----------
//      Debug  调试细节。开发阶段看，上线一般关掉。默认最低等级。
//      Info   正常运行的关键节点，比如启动、连接建立、登录成功。
//      Warn   不影响继续运行，但值得注意，比如缓存写入失败、消息投递失败。
//      Error  出错了，功能受影响，比如数据库连不上、注册失败。
//
//  等级是有序的：Debug < Info < Warn < Error。
//  setMinLevel() 设一个门槛，低于它的日志会被直接丢掉，不产生任何开销。
//
//
//  性能与线程安全
//  --------------
//  * 内部是一个单例 Logger，全局只有一份文件流和一个互斥锁。
//  * 写文件时加锁，所以多线程同时写也不会串行；等级开关用原子量，
//    判断等级时不需要加锁。
//  * 每写一行都会 flush，代价是慢一点点，换来的是程序崩溃时日志不丢。
//    日志系统本身出问题的概率，远小于它要记录的那些代码。
//
//
//  文件切分规则
//  ------------
//  默认单个文件上限 4 MB。写满之后，会把 server.log 改名成 server.1.log，
//  然后重新开始写 server.log。只保留一份历史文件，不会无限堆积。
//  用 setMaxFileSize() 可以改这个上限。
//
// ============================================================================

#include <cstddef>
#include <sstream>
#include <string>

namespace astra_log {

    // ========================================================================
    //  日志等级
    // ========================================================================

    // 等级从低到高排列，数字越大越严重。
    // 内部靠这个顺序做过滤判断，所以顺序不能乱改。
    enum class Level {
        Debug = 0, // 调试细节，只在开发阶段关心
        Info = 1, // 正常运行的关键节点
        Warn = 2, // 有问题但还能跑
        Error = 3, // 出错了，功能受影响
    };

    // 把等级转成四个字母的大写字符串，例如 Level::Info -> "INFO"。
    // 返回的是静态字符串字面量，调用方不需要释放。
    const char *levelName(Level level);


    // ========================================================================
    //  核心接口
    // ========================================================================

    // 写一条日志。
    //
    // message 是日志内容，level 是这条日志的等级。
    // 函数内部会自动加上时间戳和等级前缀，然后：
    //   * 追加写入当前日志文件（默认 server.log）
    //   * 同时打印到终端（可以用 setConsoleEnabled 关掉）
    //
    // 如果 level 低于当前设定的最低等级，这条日志会被直接丢弃。
    void log(const std::string &message, Level level);

    // 把缓冲区里的内容立刻刷到磁盘。
    // 平时每写一行都会自动 flush，这个函数只在批量写完之后想强制落盘时用。
    void flush();


    // ========================================================================
    //  设置
    // ========================================================================

    // 换一个日志文件。默认是 server.log，路径相对于程序当前工作目录。
    // 文件以「追加」方式打开，所以重启程序不会清空之前的日志。
    void setLogFile(const std::string &path);

    // 设置最低记录等级。低于它的日志会被丢掉。
    // 默认是 Level::Debug，也就是四种等级全都记。
    // 上线时通常设成 Level::Info 或 Level::Warn，可以让日志干净一些。
    void setMinLevel(Level level);

    // 是否同时把日志打印到终端，默认 true。
    // 只想让日志进文件、不刷屏的时候设成 false。
    void setConsoleEnabled(bool enabled);

    // 单个日志文件的大小上限，单位字节，默认 4 MB（4 * 1024 * 1024）。
    // 超过之后会自动把当前文件改名成 xxx.1.log，然后重新开始写。
    void setMaxFileSize(std::size_t bytes);


    // ========================================================================
    //  运行统计
    // ========================================================================

    // 从程序启动到现在，一共写了多少条、各等级各多少条。
    // 统计的是「真正写出去」的条数，被等级过滤掉的不会计入。
    struct Stats {
        std::size_t total = 0; // 总条数
        std::size_t debug = 0; // Debug 条数
        std::size_t info = 0; // Info  条数
        std::size_t warn = 0; // Warn  条数
        std::size_t error = 0; // Error 条数
    };

    // 取当前统计，返回的是一份拷贝，可以放心保存。
    Stats stats();

    // 把统计清零，一般用于做压测或者分阶段观察。
    void resetStats();


    // ========================================================================
    //  拼接工具
    // ========================================================================

    // 把任意几个值拼成一个字符串，给 log() 用。
    //
    // 这里用了 C++17 的「折叠表达式」——(oss << ... << args) 会展开成
    // oss << arg1 << arg2 << ... ，所以参数个数、类型都不限，
    // 只要这个类型能往 ostringstream 里塞就行（数字、字符串、
    // 甚至 boost 的 endpoint 都可以）。
    //
    //     astra_log::format("用户 ", name, " 上线，当前 ", count, " 人")
    template<typename... Args>
    std::string format(Args &&... args) {
        std::ostringstream oss;
        (oss << ... << args);
        return oss.str();
    }

} // namespace astra_log


// ============================================================================
//  便捷宏
// ============================================================================
//
//  直接调 log() 的话，拼接变量得手写 format()，有点啰嗦：
//      astra_log::log(astra_log::format("用户 ", name, " 上线"), astra_log::Level::Info);
//
//  用这个宏就简洁多了：
//      LOG(astra_log::Level::Info, "用户 ", name, " 上线");
//
//  宏的第一个参数是等级，后面所有的参数（__VA_ARGS__）都会原样交给
//  format() 去拼。之所以要这个宏，就是因为函数没法接收「变长参数列表」。
//
#define LOG(level, ...) ::astra_log::log(::astra_log::format(__VA_ARGS__), level)
